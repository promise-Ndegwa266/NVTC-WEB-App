require("dotenv").config
const mongodb = require("mongoose")

const URL = process.env.DATABASE_URL

async function connection() {
    if (!URL) {
        console.warn('DATABASE_URL not set; skipping DB connection for Enrollment Data');
        return;
    }
    try {
        await mongodb.connect(URL)
        console.log('Connected to DB (Enrollment Data)')
    } catch (e) {
        console.warn('DB connect failed (DormBooking):', e.message)
    }
    
}
